import assert from 'node:assert/strict';
import { test } from 'node:test';
import { auctionBinding } from '../src/modules/audit/domain/auction-binding.ts';
import { canonicalJson, hashEvent, checkChain, GENESIS_HASH } from '../src/modules/audit/domain/cryptography.ts';
import { DrizzleAuditAppender } from '../src/modules/audit/repositories/drizzle-audit-appender.ts';

const id = '11111111-1111-4111-8111-111111111111';
const seller = '22222222-2222-4222-8222-222222222222';
const product = { id, externalId:'1', source:'test', title:'Item', description:null, imageUrl:null, attributes:{ price:1.25, nested:{ b:2, a:1 } }, capturedAt:'2026-10-25T00:00:00.123456Z' };
test('v2 product commitment is stable for JSON object order, includes attributes and is separated by seller/auction', () => {
  const binding = auctionBinding(id, seller, product);
  assert.deepEqual(auctionBinding(id, seller, { ...product, attributes:{ nested:{ a:1,b:2 },price:1.25 } }),binding);
  assert.notEqual(auctionBinding(id, seller, { ...product, attributes:{ price:1.26 } }).productHash,binding.productHash);
  assert.notEqual(auctionBinding(seller,id,product).sellerRef,binding.sellerRef);
  assert.throws(()=>auctionBinding(id,seller,{...product,attributes:{n:Infinity}}));
  assert.throws(()=>auctionBinding(id,seller,{...product,attributes:{n:9007199254740992}}));
  assert.throws(()=>auctionBinding(id,seller,{...product,attributes:{n:-0}}));
  assert.throws(()=>canonicalJson({price:1.25})); // v1 numeric rules are unchanged.
});
test('v1 golden hash is unchanged; v2 and mixed-version histories cannot masquerade as v1', () => {
  const event = { id:seller,auctionId:id,sequence:1n,eventType:'AUCTION_CREATED',payload:{productSnapshotId:seller,startingBidCents:'1',minIncrementCents:'1',startsAt:'2026-10-24T12:00:00.000Z',endsAt:'2026-10-25T12:00:00.000Z',status:'PUBLISHED',currentBidId:null},createdAt:'2026-10-24T12:00:00.000Z',previousHash:GENESIS_HASH,hashVersion:1 };
  const oldHash = hashEvent(event);
  // Literal generated by the original v1 implementation before Patch01.
  assert.equal(oldHash,'031c114b63673d55bc69e347d63bf8b3fb5e780e52c2592be91101c69348d502');
  const v2 = { ...event,hashVersion:2,payload:{...event.payload,binding:auctionBinding(id,seller,product)} };
  assert.notEqual(hashEvent(v2),oldHash);
  assert.throws(()=>hashEvent({...v2,hashVersion:1}));
  assert.throws(()=>hashEvent({...event,hashVersion:2}));
  const second = { ...event,sequence:2n,eventType:'AUCTION_CLOSED_NO_BIDS',payload:{},previousHash:hashEvent(v2) };
  assert.equal(checkChain(id,[{...v2,eventHash:hashEvent(v2)},{...second,eventHash:hashEvent(second)}]).valid,false);
});
test('choosing a version never executes accessors before input validation', async () => {
  let called = 0;
  const input = { auctionId:id,eventType:'AUCTION_CREATED',createdAt:'2026-10-24T12:00:00.000Z' };
  Object.defineProperty(input,'payload',{enumerable:true,get(){called++;return {};}});
  await assert.rejects(new DrizzleAuditAppender({ select(){throw Error('must not query');} }).append(input));
  assert.equal(called,0);
});
